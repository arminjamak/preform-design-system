/**
 * Regenerates src/components/index.ts: one `export *` line per public module in each
 * component folder. Fails if two modules export the same name, so collisions surface
 * here instead of as a confusing TS error. Run with `npm run barrel`.
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('../src/components/', import.meta.url).pathname;
const SKIP = /\.(module\.css|stories\.tsx|test\.tsx?|d\.ts)$/;
// Lower-case modules are internal helpers (date maths, geometry, tokenizers…) unless listed here.
const PUBLIC_HELPERS = new Set(['Chart/scales.ts', 'Chart/useChartSize.ts', 'DataTable/types.ts']);
const isPublic = (dir, f) => /^[A-Z]/.test(f) || PUBLIC_HELPERS.has(`${dir}/${f}`);

const dirs = readdirSync(ROOT).filter((d) => statSync(join(ROOT, d)).isDirectory()).sort();
const lines = [];
const owners = new Map();
const clashes = [];

for (const dir of dirs) {
  const files = readdirSync(join(ROOT, dir))
    .filter((f) => /\.(tsx?|ts)$/.test(f) && !SKIP.test(f) && isPublic(dir, f))
    .sort((a, b) => (a.startsWith(dir + '.') ? -1 : b.startsWith(dir + '.') ? 1 : a.localeCompare(b)));
  for (const f of files) {
    const src = readFileSync(join(ROOT, dir, f), 'utf8');
    const names = new Set();
    for (const m of src.matchAll(/export\s+(?:declare\s+)?(?:const|let|function\*?|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/g)) names.add(m[1]);
    for (const m of src.matchAll(/export\s*\{([^}]*)\}(?!\s*from)/g))
      m[1].split(',').map((x) => x.trim().split(/\s+as\s+/).pop()).filter(Boolean).forEach((n) => names.add(n.replace(/^type\s+/, '')));
    if (!names.size) continue;
    const mod = `./${dir}/${f.replace(/\.tsx?$/, '')}`;
    for (const n of names) {
      if (owners.has(n) && owners.get(n) !== mod) clashes.push(`${n}: ${owners.get(n)} and ${mod}`);
      else owners.set(n, mod);
    }
    lines.push(`export * from '${mod}';`);
  }
}

if (clashes.length) {
  console.error(`✖ ${clashes.length} duplicate export name(s):\n  ${clashes.join('\n  ')}`);
  process.exit(1);
}
writeFileSync(join(ROOT, 'index.ts'), `// Generated by scripts/gen-barrel.mjs — do not edit by hand.\n${lines.join('\n')}\n`);
console.log(`✔ barrel: ${lines.length} modules from ${dirs.length} component folders, ${owners.size} exported names`);
